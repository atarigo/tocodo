/**
 * 偉業系統（紀元全域效果）。
 *
 * 設計：有人在世界中達成隱藏條件（獻祭、使用特殊道具……）時，
 * 全體玩家獲得對應效果。上線後這份資料會改由後端 API 提供；
 * 現階段用常數開關，方便本地測試手感。
 */
export interface WorldEffects {
  /** 獻祭偉業：全體攻擊加成（0.1 = +10%，0 = 未觸發） */
  攻擊聖火: number;
  /** 守護偉業：全體防禦加成（同上） */
  守護壁壘: number;
  /** 特殊道具偉業：遺產點數倍率（平時 1，觸發日 2） */
  遺產祝福: number;
}

export const WORLD_EFFECTS: WorldEffects = {
  攻擊聖火: 0,
  守護壁壘: 0,
  遺產祝福: 1,
};
